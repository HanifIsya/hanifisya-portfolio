import { chromium } from "playwright";
const b = await chromium.launch({ channel: "chrome" });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const errs = [];
p.on("pageerror", e => errs.push("pageerror: " + e.message));
p.on("console", m => { if (m.type()==="error") errs.push(m.text()); });
await p.goto("http://localhost:3000", { waitUntil: "networkidle" });
await p.waitForTimeout(2500);
await p.click('button[aria-label="Open menu"]');
await p.waitForTimeout(1200);
await p.screenshot({ path: "qa/mobile-menu.png", animations: "disabled" });
await p.click('div.fixed.inset-0.z-\\[70\\] a[href="#stack"]');
await p.waitForTimeout(1800);
const y = await p.evaluate(() => Math.round(window.scrollY));
const closed = await p.evaluate(() => !document.querySelector('div.fixed.inset-0.z-\\[70\\]'));
const locked = await p.evaluate(() => document.body.style.overflow);
console.log("after nav click -> scrollY:", y, "| menu closed:", closed, "| body overflow:", JSON.stringify(locked));
await p.screenshot({ path: "qa/mobile-after-nav.png", animations: "disabled" });
console.log("errors:", errs.length ? errs : "none");
await b.close();
